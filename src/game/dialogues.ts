export function pickDialogue(
  trigger: DialogueTrigger,
  lastId?: string,
): DialogueLine {
  const pool = DIALOGUE_LINES.filter((d) => d.trigger === trigger);
  const filtered =
    pool.length > 1 && lastId ? pool.filter((d) => d.id !== lastId) : pool;
  const list = filtered.length > 0 ? filtered : DIALOGUE_LINES;
  return list[Math.floor(Math.random() * list.length)];
}

